import { Field, ModuleDefinition } from '../core/models';
const text = (key: string, label: string, required = false, max = 160): Field => ({
  key,
  label,
  required,
  max,
});
const select = (key: string, label: string, options: string[], value?: string): Field => ({
  key,
  label,
  type: 'select',
  options,
  value,
});
const lookup = (
  key: string,
  label: string,
  source: string,
  required = false,
  multi = false,
): Field => ({ key, label, type: multi ? 'multi' : 'select', lookup: source, required });
const area = (key: string, label: string, required = false): Field => ({
  key,
  label,
  type: 'textarea',
  required,
  max: 12000,
});
const date = (key: string, label: string, required = false, time = false): Field => ({
  key,
  label,
  type: time ? 'datetime-local' : 'date',
  required,
});
const bool = (key: string, label: string, value = false): Field => ({
  key,
  label,
  type: 'checkbox',
  value,
});
const columns = (...values: string[]) =>
  values.map((v) => {
    const [key, label] = v.split(':');
    return { key, label: label || key };
  });
